export function mergePrivacyWithDefaults(
  term: {
    content?: string;
    contentEn?: string;
    contentRu?: string;
  } | null,
): { content: string; contentEn: string; contentRu: string } {
  const hasCustom =
    term?.content?.trim() || term?.contentEn?.trim() || term?.contentRu?.trim();

  if (!hasCustom) {
    return { ...DEFAULT_PRIVACY_POLICY };
  }

  return {
    content: term?.content?.trim() || DEFAULT_PRIVACY_POLICY.content,
    contentEn: term?.contentEn?.trim() || DEFAULT_PRIVACY_POLICY.contentEn,
    contentRu: term?.contentRu?.trim() || DEFAULT_PRIVACY_POLICY.contentRu,
  };
}
